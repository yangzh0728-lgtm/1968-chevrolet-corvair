import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const values=new Map();
globalThis.location={search:'',href:'http://localhost/explore/'};
globalThis.window={localStorage:{getItem:k=>values.get(k),setItem:(k,v)=>values.set(k,v)},dispatchEvent:()=>{}};
